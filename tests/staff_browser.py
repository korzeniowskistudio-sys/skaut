import os,json
from datetime import datetime,timedelta
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':1000})
 page.on('dialog',lambda dialog:dialog.accept())
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(os.environ['SKAUT_TEST_ORIGIN']+'/moj-skaut',wait_until='networkidle')
 page.get_by_label('Adres e-mail').fill(os.environ['SKAUT_TEST_EMAIL'])
 page.get_by_label('Hasło',exact=True).fill(os.environ['SKAUT_TEST_PASSWORD'])
 page.get_by_role('button',name='Zaloguj się',exact=True).click()
 page.get_by_role('link',name='Obsługa klubu',exact=True).click()
 expect(page.get_by_text('Pytanie od członka testowego',exact=True)).to_be_visible()
 thread=page.locator('#admin-message');thread.get_by_label('Odpowiedź').fill('Odpowiedź od obsługi')
 thread.get_by_role('button',name='Wyślij wiadomość').click()
 expect(page.get_by_text('Odpowiedź od obsługi',exact=True)).to_be_visible()
 form=page.locator('#admin-event')
 form.get_by_label('Nazwa wydarzenia').fill('Termin testu przeglądarki')
 form.get_by_label('Termin (czas Twojej przeglądarki)').fill((datetime.now()+timedelta(days=2)).strftime('%Y-%m-%dT%H:%M'))
 form.get_by_label('Miejsce',exact=True).fill('Lokalizacja testowa')
 form.get_by_label('Liczba miejsc').fill('5');form.get_by_label('Cena w PLN').fill('100')
 form.get_by_role('button',name='Dodaj wydarzenie').click()
 expect(page.get_by_role('heading',name='Termin testu przeglądarki',exact=True)).to_be_visible()
 event=page.locator('.booking').filter(has=page.get_by_role('heading',name='Termin testu przeglądarki',exact=True))
 event.get_by_role('button',name='Edytuj',exact=True).click()
 form.get_by_label('Nazwa wydarzenia').fill('Poprawiony termin przeglądarki')
 form.get_by_role('button',name='Zapisz zmiany').click()
 expect(page.get_by_role('heading',name='Poprawiony termin przeglądarki',exact=True)).to_be_visible()
 event=page.locator('.booking').filter(has=page.get_by_role('heading',name='Poprawiony termin przeglądarki',exact=True))
 event.get_by_role('button',name='Odwołaj',exact=True).click()
 expect(page.get_by_text('Odwołane',exact=False)).to_be_visible()
 form=page.locator('#admin-news');form.get_by_label('Tytuł',exact=True).fill('Szkic z przeglądarki')
 form.get_by_label('Adres (np. relacja-z-treningu)').fill('szkic-z-przegladarki')
 form.get_by_label('Kategoria',exact=True).fill('Test');form.get_by_label('Krótki opis').fill('Opis testowy')
 form.get_by_label('Treść',exact=True).fill('Treść testowa');form.get_by_role('button',name='Zapisz aktualność').click()
 article=page.locator('.booking').filter(has=page.get_by_role('heading',name='Szkic z przeglądarki',exact=True))
 article.get_by_role('button',name='Edytuj',exact=True).click()
 form.get_by_label('Tytuł',exact=True).fill('Poprawiony artykuł')
 form.get_by_role('button',name='Zapisz zmiany').click()
 article=page.locator('.booking').filter(has=page.get_by_role('heading',name='Poprawiony artykuł',exact=True))
 article.get_by_role('button',name='Opublikuj',exact=True).click()
 expect(article.get_by_role('button',name='Wycofaj publikację')).to_be_visible()
 page.get_by_role('navigation').get_by_role('link',name='Aktualności',exact=True).click()
 expect(page.get_by_role('heading',name='Poprawiony artykuł',exact=True)).to_be_visible()
 assert not errors, errors
 print(json.dumps({'staffBrowser':'passed','checks':['staff login','read member messages','reply','create event','edit event','cancel event','save draft','edit draft','publish draft','public news'],'pageErrors':errors}))
 browser.close()
